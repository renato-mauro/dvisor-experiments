'use strict';

/**
 * Reads results/dvisor_results.json and results/duckdb_results.json
 * and writes results/tables.tex and results/tables.md.
 *
 * Can be run standalone: node generate-tables.js
 */

const fs   = require('node:fs');
const path = require('node:path');

const DIR         = __dirname;
const RESULTS_DIR = path.join(DIR, 'results');

function loadJSON(file) {
  try { return JSON.parse(fs.readFileSync(file, 'utf8')); }
  catch { return {}; }
}

const dvisorData = loadJSON(path.join(RESULTS_DIR, 'dvisor_results.json'));
const duckdbData = loadJSON(path.join(RESULTS_DIR, 'duckdb_results.json'));

const ALL_SFS = [1, 10, 30, 50, 100];

// ── Stats ────────────────────────────────────────────────────────────────────
function median(values) {
  const s = [...values].sort((a, b) => a - b);
  const m = Math.floor(s.length / 2);
  return s.length % 2 !== 0 ? s[m] : (s[m - 1] + s[m]) / 2;
}

function aggregateRuns(runs) {
  if (!runs || !runs.length) return null;
  return {
    n:      runs.length,
    ttf:    median(runs.map(r => r.ttf)),
    tq:     median(runs.map(r => r.tq)),
    rows:   Math.round(median(runs.map(r => r.rows))),
    frames: Math.round(median(runs.map(r => r.frames || 1))),
  };
}

// ── Formatters ───────────────────────────────────────────────────────────────
function fmtS(ms) {
  return ms == null ? '—' : (ms / 1000).toFixed(3);
}

function fmtSpm(ms, sd) {
  if (ms == null) return '—';
  const s = (ms / 1000).toFixed(3);
  return sd != null ? `${s} ± ${(sd / 1000).toFixed(3)}` : s;
}

function fmtRows(n) {
  if (n == null || n === 0) return '—';
  if (n >= 1e9) return (n / 1e9).toFixed(2) + 'G';
  if (n >= 1e6) return (n / 1e6).toFixed(2) + 'M';
  if (n >= 1e3) return (n / 1e3).toFixed(1) + 'K';
  return String(Math.round(n));
}

function fmtSpeed(tq, rows) {
  if (!tq || !rows) return '—';
  return ((rows / 1e6) / (tq / 1000)).toFixed(2);
}

function srcLabel(source) {
  return source === 'local' ? 'LAN' : 'WAN';
}

// ── LaTeX helpers ─────────────────────────────────────────────────────────────
function latexEsc(s) {
  return String(s).replace(/[%&#_{}]/g, c => '\\' + c).replace(/~/, '\\textasciitilde{}');
}

function latexTable(caption, label, headers, rows) {
  const colSpec  = 'r' + 'r'.repeat(headers.length - 1);
  const headLine = headers.map(h => `\\textbf{${latexEsc(h)}}`).join(' & ');
  const body     = rows.map(r => r.map(latexEsc).join(' & ') + ' \\\\').join('\n    ');
  return [
    '\\begin{table}[htbp]',
    '  \\centering',
    `  \\caption{${latexEsc(caption)}}`,
    `  \\label{${label}}`,
    `  \\begin{tabular}{${colSpec}}`,
    '    \\toprule',
    `    ${headLine} \\\\`,
    '    \\midrule',
    `    ${body}`,
    '    \\bottomrule',
    '  \\end{tabular}',
    '\\end{table}',
    '',
  ].join('\n');
}

// ── Markdown helpers ──────────────────────────────────────────────────────────
function mdTable(title, headers, rows) {
  const sep  = headers.map(() => '---').join(' | ');
  const head = '| ' + headers.join(' | ') + ' |';
  const body = rows.map(r => '| ' + r.join(' | ') + ' |').join('\n');
  return [`### ${title}`, '', head, `| ${sep} |`, body, ''].join('\n');
}

// ── Build table rows for one (source × threads × query) Dvisor group ─────────
function dvisorTableRows(sfMap) {
  return ALL_SFS.map(sf => {
    const agg = aggregateRuns(sfMap?.[String(sf)]);
    if (!agg) return [String(sf) + '×', '—', '—', '—', '—', '—', '—', '—'];
    return [
      String(sf) + '×',
      String(agg.n),
      fmtS(agg.ttf),
      fmtS(agg.tq),
      fmtRows(agg.rows),
      fmtSpeed(agg.tq, agg.rows),
      String(agg.frames),
      agg.tq > 0 && agg.frames > 0 ? (agg.frames / (agg.tq / 1000)).toFixed(2) : '—',
    ];
  });
}

const DVISOR_HEADERS = ['SF', 'N', 'TTF (s)', 'TQ (s)', 'Rows', 'Speed (MR/s)', 'Frames', 'FPS'];

// ── Build table rows for one (source × query) DuckDB group ───────────────────
function duckdbTableRows(sfMap) {
  return ALL_SFS.map(sf => {
    const agg = aggregateRuns(sfMap?.[String(sf)]);
    if (!agg) return [String(sf) + '×', '—', '—', '—', '—'];
    return [
      String(sf) + '×',
      String(agg.n),
      fmtS(agg.tq),
      fmtRows(agg.rows),
      fmtSpeed(agg.tq, agg.rows),
    ];
  });
}

const DUCKDB_HEADERS = ['SF', 'N', 'TQ (s)', 'Rows', 'Speed (MR/s)'];

// ── Assemble output ───────────────────────────────────────────────────────────
const texParts = [
  '% Auto-generated by generate-tables.js — do not edit manually',
  '% Requires: \\usepackage{booktabs}',
  '',
];
const mdParts = [
  '# Experiment Results',
  '',
  '> Auto-generated by `generate-tables.js`',
  '',
];

// Dvisor tables
mdParts.push('## Dvisor', '');

for (const source of Object.keys(dvisorData).sort()) {
  for (const threads of Object.keys(dvisorData[source]).sort((a, b) => +a - +b)) {
    for (const query of Object.keys(dvisorData[source][threads]).sort()) {
      const sfMap  = dvisorData[source][threads][query];
      const src    = srcLabel(source);
      const title  = `Dvisor — ${src}, ${threads}T, ${query.toUpperCase()}`;
      const cap    = `Dvisor: source=${src}, threads=${threads}, query=${query.toUpperCase()}`;
      const lbl    = `tab:dvisor_${source}_${threads}t_${query}`;
      const rows   = dvisorTableRows(sfMap);

      texParts.push(latexTable(cap, lbl, DVISOR_HEADERS, rows));
      mdParts.push(mdTable(title, DVISOR_HEADERS, rows));
    }
  }
}

// DuckDB tables
mdParts.push('## DuckDB', '');

for (const source of Object.keys(duckdbData).sort()) {
  for (const query of Object.keys(duckdbData[source]).sort()) {
    const sfMap = duckdbData[source][query];
    const src   = srcLabel(source);
    const title = `DuckDB — ${src}, ${query.toUpperCase()}`;
    const cap   = `DuckDB-WASM: source=${src}, query=${query.toUpperCase()}`;
    const lbl   = `tab:duckdb_${source}_${query}`;
    const rows  = duckdbTableRows(sfMap);

    texParts.push(latexTable(cap, lbl, DUCKDB_HEADERS, rows));
    mdParts.push(mdTable(title, DUCKDB_HEADERS, rows));
  }
}

// ── Comparison tables (Dvisor 4T + DuckDB, per source × query) ───────────────
mdParts.push('## Comparison (Dvisor 4T vs DuckDB)', '');

const CMP_HEADERS = ['SF', 'Dv TTF (s)', 'Dv TQ (s)', 'Dv Frames', 'DK TQ (s)', 'Speedup'];

for (const source of [...new Set([...Object.keys(dvisorData), ...Object.keys(duckdbData)])].sort()) {
  for (const query of ['q01', 'q02', 'q03']) {
    const dvSfMap = dvisorData?.[source]?.['4']?.[query];
    const dkSfMap = duckdbData?.[source]?.[query];
    if (!dvSfMap && !dkSfMap) continue;

    const sfs = ALL_SFS;
    const src = srcLabel(source);
    const title = `Comparison — ${src}, ${query.toUpperCase()} (Dvisor 4T vs DuckDB)`;
    const cap   = `Comparison: source=${src}, query=${query.toUpperCase()}, Dvisor 4T vs DuckDB-WASM`;
    const lbl   = `tab:cmp_${source}_${query}`;

    const rows = sfs.map(sf => {
      const dvAgg = aggregateRuns(dvSfMap?.[String(sf)]);
      const dkAgg = aggregateRuns(dkSfMap?.[String(sf)]);
      const speedup = dvAgg && dkAgg
        ? (dkAgg.tq / dvAgg.tq).toFixed(2) + '×'
        : '—';
      return [
        String(sf) + '×',
        dvAgg ? fmtS(dvAgg.ttf) : '—',
        dvAgg ? fmtS(dvAgg.tq)  : '—',
        dvAgg ? String(dvAgg.frames) : '—',
        dkAgg ? fmtS(dkAgg.tq)  : '—',
        speedup,
      ];
    });

    texParts.push(latexTable(cap, lbl, CMP_HEADERS, rows));
    mdParts.push(mdTable(title, CMP_HEADERS, rows));
  }
}

// ── localStorage import script ────────────────────────────────────────────────
// Paste into the browser console while figures.html (or any page on the same
// origin) is open. It writes both result stores to localStorage and reloads.
const importScript = [
  '// Generated by generate-tables.js — paste in the browser console while',
  '// figures.html (or any page on localhost:8080) is open.',
  `localStorage.setItem('dvisor_results', ${JSON.stringify(JSON.stringify(dvisorData))});`,
  `localStorage.setItem('duckdb_results', ${JSON.stringify(JSON.stringify(duckdbData))});`,
  "console.log('✓ dvisor_results and duckdb_results loaded into localStorage');",
  'location.reload();',
].join('\n');

// ── Write files ───────────────────────────────────────────────────────────────
fs.mkdirSync(RESULTS_DIR, { recursive: true });

const texOut    = path.join(RESULTS_DIR, 'tables.tex');
const mdOut     = path.join(RESULTS_DIR, 'tables.md');
const importOut = path.join(RESULTS_DIR, 'import-to-localStorage.js');

fs.writeFileSync(texOut,    texParts.join('\n'));
fs.writeFileSync(mdOut,     mdParts.join('\n'));
fs.writeFileSync(importOut, importScript);

console.log('Tables written:');
console.log(`  ${texOut}`);
console.log(`  ${mdOut}`);
console.log(`  ${importOut}  ← paste in browser console to load results into localStorage`);
